// Regenerates assets/images/dapr_hero_diagram.svg, the static fallback for the
// homepage hero diagram, from the diagram itself: builds the site, renders the
// homepage with reduced motion (the still frame), and saves the drawn svg as a
// standalone file. Run after changing hero-diagram.js:  npm run export:hero-fallback
import { spawn, spawnSync } from 'node:child_process';
import { rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from '@playwright/test';

const PORT = 8190;
const repoRoot = resolve(import.meta.dirname, '..');
const dir = 'tests/.site-fallback';
const out = resolve(repoRoot, 'assets/images/dapr_hero_diagram.svg');

const build = spawnSync('hugo', ['--quiet', '--cleanDestinationDir', '--baseURL', `http://localhost:${PORT}/`, '--destination', dir],
  { cwd: repoRoot, encoding: 'utf8' });
if (build.status !== 0) throw new Error(`hugo failed:\n${build.stderr}`);

const server = spawn('node', ['tests/serve.js', dir, String(PORT)], { cwd: repoRoot, stdio: 'ignore' });
const browser = await chromium.launch({ channel: 'chrome' });
try {
  const page = await browser.newPage({ reducedMotion: 'reduce' });
  for (let i = 0; i < 50; i++) {
    try { await page.goto(`http://localhost:${PORT}/`); break; } catch { await page.waitForTimeout(100); }
  }
  await page.locator('.hero-diagram-svg circle').first().waitFor({ state: 'attached' });
  const svg = await page.evaluate(() => {
    const src = document.querySelector('.hero-diagram-svg');
    const el = src.cloneNode(true);
    el.querySelector('.hero-diagram-fallback')?.remove();
    for (const a of ['class', 'role', 'aria-labelledby']) el.removeAttribute(a);
    // the page's font does not reach an svg loaded as an image; name it, with fallbacks
    el.setAttribute('font-family', '"Noto Sans", Arial, Helvetica, sans-serif');
    el.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
    el.setAttribute('width', '640');
    el.setAttribute('height', '515');
    return el.outerHTML;
  });
  writeFileSync(out, `<!-- Generated by tests/export-hero-fallback.js. Do not edit by hand. -->\n${svg}\n`);
  console.log(`wrote ${out} (${svg.length} bytes)`);
} finally {
  await browser.close();
  server.kill();
  rmSync(resolve(repoRoot, dir), { recursive: true, force: true });
}
